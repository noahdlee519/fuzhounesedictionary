-- ============================================================================
--  search_pinyin.sql — find a word by its Mandarin pinyin.
--  27 Oct 2026. Run AFTER search_v3.sql (already run on the live site), in
--  Supabase → SQL Editor. Safe to re-run.
--
--  Before this file, searching "dingbianhu" — how most people who grew up with
--  Mandarin would spell 鼎邊糊 — found a rattan shield (dìng-bà̤, a close
--  match on the letters) and not the dish, which the dictionary writes
--  diāng-biĕng-gù. Someone who knows a word by its Mandarin name had to type
--  the characters.
--
--  1. entries.pinyin: each word's Mandarin reading, folded the way search
--     folds romanization (no tone marks, no spaces): "dingbianhu". A word
--     read more than one way keeps each, separated by a space; ü is kept as
--     both u and v ("lu lv"), the two ways people type it.
--
--  2. Filled for the words already here, from two sources:
--     · Wiktionary's reading, for the 2,599 words imported from it (in the
--       word's notes, "Mandarin: dǐngbiānhú."), where it is written out in
--       full. Some are shorthand that mixes in characters ("Mandarin: 閩jù",
--       "shì場") — those are skipped and read as below instead.
--     · For the rest, a reading worked out from the characters (pinyin-pro,
--       after converting to simplified). Checked against Wiktionary's where
--       both exist. Words with a Fuzhou-only character (𡳞, 𣍐, 䁐 …) get
--       none, rather than a reading of half their syllables.
--     Words added or edited from now on get theirs from the site (an
--     editor's save, an approval, or the Add a word form): src/lib/pinyin.ts.
--
--  3. search_entries(): search_v3 plus the reading. The whole reading ranks
--     with a whole-word English match (2); the start of it, five letters or
--     more, with a meaning that begins with the query (4). Not tried when the
--     query is an English word found in the dictionary's meanings: "hair",
--     "change", "she" and "fan" are pinyin too (孩兒, 嫦娥, 蛇, 飯), and those
--     searches are for the English.
--
--  4. When a word's characters change, its reading is cleared, so it never
--     describes characters the word no longer has; the site refills it.
--
--  5. Also fixed: "%" and "_" matched every word again (search_v3 compared
--     the folded query unescaped). They now match only themselves.
-- ============================================================================

alter table public.entries add column if not exists pinyin text;

-- 4 ------------------------------------------------------------------------
create or replace function public.entries_pinyin_reset()
returns trigger
language plpgsql
as $$
begin
  if new.hanzi is distinct from old.hanzi and new.pinyin is not distinct from old.pinyin then
    new.pinyin := null;
  end if;
  return new;
end;
$$;

drop trigger if exists entries_pinyin_reset on public.entries;
create trigger entries_pinyin_reset
  before update of hanzi on public.entries
  for each row execute function public.entries_pinyin_reset();

-- 2 ------------------------------------------------------------------------
-- Wiktionary's reading, where it is written out in full.
update public.entries e
   set pinyin = w.p
  from (
    select id, string_agg(distinct f, ' ' order by f) as p
      from (
        select x.id, public.fz_fold(v) as f
          from public.entries x
          cross join lateral unnest(string_to_array(substring(x.notes from 'Mandarin: ([^.]+)\.'), ',')) part
          -- ü as v too; decomposed first, so ǖ ǘ ǚ ǜ count as well
          cross join lateral unnest(array[part, replace(normalize(part, NFD), 'u' || chr(776), 'v')]) v
         where x.notes like '%Mandarin: %'
           and part not like '%=%'
      ) t
     where f ~ '^[a-z]+$'
     group by id
  ) w
 where w.id = e.id
   and e.pinyin is distinct from w.p;

